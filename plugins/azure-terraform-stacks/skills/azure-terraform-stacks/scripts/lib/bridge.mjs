// "bridge": Terraform outputs -> Kustomize overlay, optionally as a pull request (gh / az repos).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";

const MARK = /#\s*bridge:\s*([\w-]+)\s*$/;

export function applyOutputs(text, outputs) {
  const used = new Set();
  const lines = text.split("\n").map((line) => {
    const m = MARK.exec(line);
    if (!m) return line;
    const name = m[1];
    if (!(name in outputs)) return line;
    used.add(name);
    const value = String(outputs[name].value);
    // "- KEY=<value> # bridge: x"  or  'value: "<value>" # bridge: x'
    if (/^\s*-\s*[\w.-]+=/.test(line)) return line.replace(/^(\s*-\s*[\w.-]+=)\S*(\s+#)/, `$1${value}$2`);
    return line.replace(/^(\s*value:\s*)"[^"]*"(\s+#)/, `$1"${value}"$2`);
  });
  return { text: lines.join("\n"), used };
}

function sh(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: "utf8", ...opts });
  return { ok: r.status === 0, out: (r.stdout ?? "").trim(), err: (r.stderr ?? "").trim() || (r.error ? String(r.error.message) : "") };
}

export function detectProvider(url) {
  if (/github\.com[:/]/.test(url)) return "github";
  if (/dev\.azure\.com|visualstudio\.com/.test(url)) return "azure-repos";
  return null;
}

export function bridge(root, m, { stack, env, instance, outputsFile, openPr = false, provider = null, base = null }) {
  const apps = (m.gitops?.apps ?? []).filter((a) => a.stack === stack);
  if (!apps.length) return { ok: false, message: `no GitOps app reads the outputs of ${stack}` };
  let outputs;
  try { outputs = JSON.parse(readFileSync(outputsFile, "utf8")); } catch (e) { return { ok: false, message: `cannot read ${outputsFile}: ${e.message}` }; }

  // refuse sensitive outputs before writing anything
  for (const a of apps) for (const out of Object.values(a.values)) {
    if (!(out in outputs)) return { ok: false, message: `output ${out} (mapped in gitops.apps.${a.name}.values) is not in ${outputsFile}` };
    if (outputs[out].sensitive) return { ok: false, message: `output ${out} is sensitive; secrets never go to Git (read them from Key Vault)` };
  }

  const changed = [];
  const overlays = [];
  for (const a of apps) {
    const path = `infra/argocd/manifests/${a.name}/overlays/${env}-${instance}/kustomization.yaml`;
    const abs = join(root, path);
    if (!existsSync(abs)) return { ok: false, message: `${path} does not exist; run scaffold first` };
    overlays.push(path);
    const before = readFileSync(abs, "utf8");
    const { text } = applyOutputs(before, outputs);
    if (text !== before) { writeFileSync(abs, text); changed.push(path); }
  }
  if (!openPr) return { ok: true, changed, message: changed.length ? `updated ${changed.join(", ")}` : "overlay already holds these outputs" };
  // What goes in the pull request is what differs from HEAD, including a change kept
  // on disk by an earlier run that could not open the pull request.
  const pending = overlays.filter((p) => !sh("git", ["diff", "--quiet", "HEAD", "--", p], { cwd: root }).ok);
  if (!pending.length) return { ok: true, changed, message: "overlay already holds these outputs; no pull request opened" };

  // pull request
  const remote = sh("git", ["remote", "get-url", "origin"], { cwd: root });
  const kind = provider ?? detectProvider(remote.out);
  if (!kind) return { ok: false, changed, message: `cannot tell the Git provider from origin (${remote.out || "no origin"}); pass --provider github or azure-repos. The overlay change is kept on disk.` };
  const cli = kind === "github" ? "gh" : "az";
  const auth = kind === "github" ? sh("gh", ["auth", "status"], { cwd: root }) : sh("az", ["account", "show"], { cwd: root });
  if (!auth.ok) return { ok: false, changed, message: `${cli} is missing or not logged in (${auth.err.split("\n")[0]}). Run ${kind === "github" ? "gh auth login" : "az login (and az extension add --name azure-devops)"}, then rerun. The overlay change is kept on disk.` };

  const hash = createHash("sha256").update(pending.map((p) => readFileSync(join(root, p), "utf8")).join("\n")).digest("hex").slice(0, 8);
  const branch = `bridge/${stack}-${env}-${instance}-${hash}`;
  const target = base ?? (sh("git", ["symbolic-ref", "--short", "refs/remotes/origin/HEAD"], { cwd: root }).out.replace(/^origin\//, "") || "main");
  const title = `chore(gitops): bridge ${stack} outputs to ${env}-${instance}`;
  const body = `Writes the Terraform outputs of ${stack} (${env}-${instance}) into the Kustomize overlay. Generated by azure-terraform-stacks bridge; no secret values.`;

  const existing = kind === "github"
    ? sh("gh", ["pr", "list", "--head", branch, "--state", "open", "--json", "url", "--jq", ".[0].url"], { cwd: root })
    : sh("az", ["repos", "pr", "list", "--source-branch", branch, "--status", "active", "--query", "[0].pullRequestId", "-o", "tsv"], { cwd: root });
  if (existing.ok && existing.out) return { ok: true, changed, pr: existing.out, message: `a pull request for ${branch} is already open: ${existing.out}` };

  const steps = [
    ["git", ["checkout", "-B", branch]],
    ["git", ["add", ...pending]],
    ["git", ["commit", "-m", title]],
    ["git", ["push", "-u", "origin", branch]],
  ];
  for (const [c, a] of steps) {
    const r = sh(c, a, { cwd: root });
    if (!r.ok) return { ok: false, changed, message: `${c} ${a.join(" ")} failed: ${r.err}` };
  }
  const pr = kind === "github"
    ? sh("gh", ["pr", "create", "--head", branch, "--base", target, "--title", title, "--body", body], { cwd: root })
    : sh("az", ["repos", "pr", "create", "--source-branch", branch, "--target-branch", target, "--title", title, "--description", body, "--query", "pullRequestId", "-o", "tsv"], { cwd: root });
  if (!pr.ok) return { ok: false, changed, message: `opening the pull request failed: ${pr.err}. The branch ${branch} is pushed.` };
  return { ok: true, changed, branch, pr: pr.out, message: `opened ${pr.out} from ${branch}; it is not merged` };
}
