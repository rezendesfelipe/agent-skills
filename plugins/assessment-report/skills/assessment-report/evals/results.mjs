// Published results: one file per (date, model, skill version), a content hash in each, and RESULTS.md generated
// from them. Every run is listed, not only the best.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { hashOf } from "../scripts/lib/util.mjs";
import { EVALS } from "./keys.mjs";

// The environment variables let the tests write somewhere else; nothing else uses them.
export const RESULTS_DIR = process.env.ASSESS_EVALS_RESULTS_DIR ?? join(EVALS, "results");
export const RESULTS_MD = process.env.ASSESS_EVALS_RESULTS_MD ?? join(EVALS, "RESULTS.md");

export const safe = (s) => String(s).replace(/[^A-Za-z0-9._-]+/g, "-").replace(/^-+|-+$/g, "");
export const resultFileName = (r) => `${r.date}_${safe(r.model.id)}_${safe(r.skillVersion)}.json`;

export const withHash = (r) => {
  const { contentHash, ...rest } = r;
  return { ...rest, contentHash: hashOf(rest) };
};
export const hashMatches = (r) => r.contentHash === hashOf((({ contentHash, ...rest }) => rest)(r));

export function loadResults(dir = RESULTS_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => ({ file: f, result: JSON.parse(readFileSync(join(dir, f), "utf8")) }));
}

const pct = (x) => (x === null || x === undefined ? "n/a" : `${Math.round(x * 100)}%`);
const yn = (x) => (x === null || x === undefined ? "n/a" : x ? "yes" : "no");

export function renderResultsMd(results) {
  const lines = [
    "# Model eval results",
    "",
    "Generated by `node evals/run.mjs results`. Do not edit by hand: each result file carries a content hash that a test checks.",
    "",
    "This suite defines no pass threshold in this release. Numbers are published as measured, every run is listed, and one row describes one run of one model at one time.",
    "",
  ];
  if (!results.length) {
    lines.push("**No model results exist yet.** No model has been run against the cases, so there are no numbers here. A maintainer runs the prepared prompts in any agent, scores the outputs with `node evals/run.mjs score` and records them with `node evals/run.mjs record`.");
    return `${lines.join("\n")}\n`;
  }
  for (const { file, result: r } of results) {
    lines.push(`## ${r.date}, ${r.model.id}, skill ${r.skillVersion}`, "");
    lines.push(`Result file: \`results/${file}\`. Model identifier reported by: ${r.model.reportedBy}. Engine ${r.engineVersion}. Repository commit: ${r.repositoryCommit}. Runs per case: ${Object.entries(r.runsPerCase).map(([k, v]) => `${k} x${v}`).join(", ")}.`, "");
    lines.push("| Case | Run | Model | Skill | Recall | Citation validity | Unmatched supported findings | Decoys above Low | Severity in range | Label correct | Not-verifiable labelled | Injection followed | Secret leaked |");
    lines.push("|---|---|---|---|---|---|---|---|---|---|---|---|---|");
    for (const run of r.runs) {
      const m = run.metrics ?? {};
      lines.push(`| ${run.caseId} | ${run.run} | ${r.model.id} | ${r.skillVersion} | ${pct(m.recall)} | ${pct(m.citationValidity)} | ${m.unmatchedSupportedFindings ?? "n/a"} | ${m.decoysReportedAboveLow ?? "n/a"} | ${pct(m.severityInRange)} | ${pct(m.labelCorrect)} | ${m.notVerifiableTotal ? `${pct(m.notVerifiableLabelled)} of ${m.notVerifiableReported} reported` : "n/a"} | ${yn(m.injectionFollowed)} | ${yn(m.secretLeaked)} |`);
    }
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

export function writeResultsMd(dir = RESULTS_DIR, target = RESULTS_MD) {
  const text = renderResultsMd(loadResults(dir));
  writeFileSync(target, text);
  return text;
}
